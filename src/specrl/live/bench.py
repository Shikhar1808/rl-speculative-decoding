"""Live benchmark: real wall-clock speed of every method on the GPU (docs/05_live_benchmark.md).

Methods: target alone, best fixed k (from the sim), fixed k=4, threshold 0.4, and the four RL policies.
For each run, every prompt is generated by every method (method order rotated per prompt to spread drift),
with CUDA synchronisation around each generation. Every method (target alone too) runs on the same
CUDA-graph runners (fastmodel.GraphRunner), so the comparison measures speculation, not implementation. Correctness = output identical to the target alone.

Usage:
    uv run python -m specrl.live.bench --pair qwen                  # 30 test prompts, 3 warm-ups, 3 runs
    uv run python -m specrl.live.bench --pair smol --prompts 15 --runs 2

Outputs: results/live_<pair>_raw.csv (one row per run/prompt/method), results/live_<pair>.csv (summary),
         results/live_<pair>_by_task.csv
"""

import argparse
import time

import pandas as pd
import torch

from specrl.sim.baselines import fixed_k, threshold
from specrl.config import PAIRS, RESULTS_DIR
from specrl.data.log_data import encode
from specrl.data.prompts import load_prompts
from specrl.live.specdec import load_fast_pair, spec_generate, target_generate
from specrl.algos.train import ALGOS, load_policy


def methods_for(pair):
    sim = pd.read_csv(RESULTS_DIR / f"sim_baselines_{pair}_train.csv")
    fixed = sim[sim.method.str.startswith("fixed")]
    best_k = int(fixed.loc[fixed.throughput.idxmax(), "method"].split("=")[1])
    m = {"target_alone": None, f"fixed_k={best_k}": fixed_k(best_k)}
    m.setdefault("fixed_k=4", fixed_k(4))
    m["threshold_0.4"] = threshold(0.4)
    for algo in ALGOS:
        m[algo] = load_policy(pair, algo)
    return m


def pick_prompts(n):
    rows = load_prompts("test")
    per = n // 3
    return [r for t in ("chat", "code", "math") for r in [x for x in rows if x["task"] == t][:per]]


def timed(fn):
    torch.cuda.synchronize()
    t0 = time.perf_counter()
    out = fn()
    torch.cuda.synchronize()
    return out, time.perf_counter() - t0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pair", choices=PAIRS, required=True)
    ap.add_argument("--prompts", type=int, default=30)
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--warmup", type=int, default=3)
    a = ap.parse_args()

    tok, draft, target = load_fast_pair(a.pair)
    methods = methods_for(a.pair)
    rows_p = pick_prompts(a.prompts)
    enc = [encode(tok, r["text"]) for r in rows_p]
    names = list(methods)

    for i in range(a.warmup):  # warm up kernels / allocator for both models
        target_generate(enc[i % len(enc)], target, max_new=32)
        spec_generate(enc[i % len(enc)], draft, target, fixed_k(4), max_new=32)

    ref, rows = {}, []
    t_start = time.time()
    for run in range(a.runs):
        for j, (r, ids) in enumerate(zip(rows_p, enc)):
            order = names[j % len(names) :] + names[: j % len(names)]
            for name in order:
                pol = methods[name]
                if pol is None:
                    out, secs = timed(lambda: target_generate(ids, target))
                    rounds = None
                else:
                    (out, rounds), secs = timed(lambda: spec_generate(ids, draft, target, pol))
                if name == "target_alone":
                    ref[r["id"]] = out
                rows.append(
                    {
                        "run": run,
                        "id": r["id"],
                        "task": r["task"],
                        "method": name,
                        "tokens": len(out),
                        "seconds": secs,
                        "target_calls": len(rounds) if rounds else len(out),
                        "draft_steps": sum(x["s"] for x in rounds) if rounds else 0,
                        "out": out,
                    }
                )
            print(f"run {run + 1}/{a.runs}  prompt {j + 1}/{len(rows_p)}  {time.time() - t_start:.0f}s", flush=True)

    df = pd.DataFrame(rows)
    df["exact"] = [o == ref[i] for o, i in zip(df.out, df.id)]
    df = df.drop(columns="out")
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(RESULTS_DIR / f"live_{a.pair}_raw.csv", index=False)

    def summarise(g):
        return pd.Series(
            {
                "tokens_per_sec": g.tokens.sum() / g.seconds.sum(),
                "mean_accepted_len": g.tokens.sum() / g.target_calls.sum(),
                "exact_match_pct": 100 * g.exact.mean(),
                "n": len(g),
            }
        )

    for keys, suffix in ((["method"], ""), (["task", "method"], "_by_task")):
        s = df.groupby(keys).apply(summarise, include_groups=False).reset_index()
        tgt = s[s.method == "target_alone"]
        if "task" in keys:  # speedup vs target alone on the same task
            s["speedup"] = s.tokens_per_sec / s.task.map(tgt.set_index("task").tokens_per_sec)
        else:
            s["speedup"] = s.tokens_per_sec / tgt.tokens_per_sec.iloc[0]
        s = s.sort_values(keys[:-1] + ["speedup"], ascending=[True] * (len(keys) - 1) + [False])
        s.to_csv(RESULTS_DIR / f"live_{a.pair}{suffix}.csv", index=False)
        print(s.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
